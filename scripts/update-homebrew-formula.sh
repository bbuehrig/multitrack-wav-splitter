#!/usr/bin/env bash
# Generate Formula/mtwav-split.rb and push it to the Homebrew tap.
# Requires: dist/ binaries, HOMEBREW_TAP_TOKEN (PAT with contents:write on the tap).
#
# Env:
#   VERSION              e.g. v0.2.0 or 0.2.0 (required)
#   HOMEBREW_TAP_TOKEN   GitHub token for bbuehrig/homebrew-tap (required)
#   HOMEBREW_TAP_OWNER   default: bbuehrig
#   HOMEBREW_TAP_REPO    default: homebrew-tap
#   DIST_DIR             default: ./dist
#   GITHUB_REPOSITORY    owner/name of this project (for release URLs)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIST_DIR="${DIST_DIR:-${ROOT}/dist}"
VERSION="${VERSION:-${1:-}}"
VERSION="${VERSION#v}"
TAP_OWNER="${HOMEBREW_TAP_OWNER:-bbuehrig}"
TAP_REPO="${HOMEBREW_TAP_REPO:-homebrew-tap}"
PROJECT_REPO="${GITHUB_REPOSITORY:-bbuehrig/multitrack-wav-splitter}"
TOKEN="${HOMEBREW_TAP_TOKEN:-}"

if [[ -z "${VERSION}" ]]; then
  echo "VERSION is required (e.g. 0.2.0)" >&2
  exit 1
fi

if [[ -z "${TOKEN}" ]]; then
  echo "HOMEBREW_TAP_TOKEN not set — skipping Homebrew tap update." >&2
  exit 0
fi

need() {
  local f="$1"
  if [[ ! -f "${DIST_DIR}/${f}" ]]; then
    echo "missing binary: ${DIST_DIR}/${f}" >&2
    exit 1
  fi
}

need mtwav-split_darwin_arm64
need mtwav-split_darwin_amd64
need mtwav-split_linux_arm64
need mtwav-split_linux_amd64

sha() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{ print $1 }'
  else
    shasum -a 256 "$1" | awk '{ print $1 }'
  fi
}

SHA_DARWIN_ARM64="$(sha "${DIST_DIR}/mtwav-split_darwin_arm64")"
SHA_DARWIN_AMD64="$(sha "${DIST_DIR}/mtwav-split_darwin_amd64")"
SHA_LINUX_ARM64="$(sha "${DIST_DIR}/mtwav-split_linux_arm64")"
SHA_LINUX_AMD64="$(sha "${DIST_DIR}/mtwav-split_linux_amd64")"

BASE="https://github.com/${PROJECT_REPO}/releases/download/v${VERSION}"

FORMULA_DIR="$(mktemp -d)"
trap 'rm -rf "${FORMULA_DIR}"' EXIT

mkdir -p "${FORMULA_DIR}/Formula"
cat > "${FORMULA_DIR}/Formula/mtwav-split.rb" <<EOF
# typed: false
# frozen_string_literal: true

# This file is generated by multitrack-wav-splitter CI (scripts/update-homebrew-formula.sh).
class MtwavSplit < Formula
  desc "Split multitrack WAV files into mono WAVs (e.g. Behringer X32 / X-Live)"
  homepage "https://github.com/${PROJECT_REPO}"
  version "${VERSION}"
  license "CC0-1.0"

  on_macos do
    on_arm do
      url "${BASE}/mtwav-split_darwin_arm64"
      sha256 "${SHA_DARWIN_ARM64}"
    end
    on_intel do
      url "${BASE}/mtwav-split_darwin_amd64"
      sha256 "${SHA_DARWIN_AMD64}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/mtwav-split_linux_arm64"
      sha256 "${SHA_LINUX_ARM64}"
    end
    on_intel do
      url "${BASE}/mtwav-split_linux_amd64"
      sha256 "${SHA_LINUX_AMD64}"
    end
  end

  def install
    bin.install Dir["mtwav-split_*"].first => "mtwav-split"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mtwav-split -version").strip
  end
end
EOF

WORKDIR="$(mktemp -d)"
trap 'rm -rf "${FORMULA_DIR}" "${WORKDIR}"' EXIT

git clone --depth 1 "https://x-access-token:${TOKEN}@github.com/${TAP_OWNER}/${TAP_REPO}.git" "${WORKDIR}/tap"
mkdir -p "${WORKDIR}/tap/Formula"
cp "${FORMULA_DIR}/Formula/mtwav-split.rb" "${WORKDIR}/tap/Formula/mtwav-split.rb"

# Keep a short README in the tap if missing.
if [[ ! -f "${WORKDIR}/tap/README.md" ]]; then
  cat > "${WORKDIR}/tap/README.md" <<EOF
# Homebrew tap

\`\`\`bash
brew install ${TAP_OWNER}/tap/mtwav-split
brew upgrade mtwav-split
\`\`\`

Formulae are updated automatically from [${PROJECT_REPO}](https://github.com/${PROJECT_REPO}) releases.
EOF
fi

cd "${WORKDIR}/tap"
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git add Formula/mtwav-split.rb README.md
if git diff --cached --quiet; then
  echo "Homebrew formula unchanged."
  exit 0
fi
git commit -m "mtwav-split ${VERSION}"
git push origin HEAD:main
echo "Updated ${TAP_OWNER}/${TAP_REPO} Formula/mtwav-split.rb → ${VERSION}"
